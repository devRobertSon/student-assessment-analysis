const BY_TYPE = new Map<string, TypeGuide>();
for (const g of [...MATH_GUIDE, ...SCIENCE_GUIDE]) {
  // 두 과목에 `개념 이해` 가 같이 있다. 리포트는 한 과목만 담으므로 과목을
  // 받아 가려낸다.
  BY_TYPE.set(`${g.area ? '수학' : '과학'}|${g.type}`, g);
}

/** 그 과목의 유형 풀이. 없으면 undefined. */
export function guideOf(subject: string, type: string): TypeGuide | undefined {
  return BY_TYPE.get(`${subject === '과학' ? '과학' : '수학'}|${type}`);
}

/** 그 과목이 영역으로 묶이는가. 수학만 둘씩 묶인다. */
export function hasAreas(subject: string): boolean {
  return subject !== '과학';
}
