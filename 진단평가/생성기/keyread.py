CIRCLE = '①②③④⑤'
TAG = {'입학 심화형': 'A', '심화': 'B', '응용': 'C', '기본': 'E'}


def norm(s):
    """동그라미 번호가 있으면 그것만, 없으면 단위·공백을 털어 낸 값으로 비교한다."""
    c = ''.join(ch for ch in s if ch in CIRCLE)
    if c:
        return c
    s = s.replace('−', '-').replace('–', '-')
    s = re.sub(r'(cm|km|m|g|원|개|장|초|분|명|점|회|일|기압|°|²|³|\s)', '', s)
    return s


def main():
    ok, bad, miss = [], [], []
    for f, g in [('spec_m11.json', '중1-1'), ('spec_m12.json', '중1-2'),
                 ('spec_m21.json', '중2-1'), ('spec_m22.json', '중2-2')]:
        s = json.load(io.open(f, encoding='utf-8'))
        for i, q in enumerate(s['questions'], 1):
            m = re.search(r'\((중\d-\d)\)', q['src'])
            src = '%s_%s' % (m.group(1) if m else g, TAG[q['src'].split(' (')[0]])
            got = KEY.get(src, {}).get(q['srcno'])
            row = (s['title'], i, src, q['srcno'], got, q['answer'])
            if got is None:
                miss.append(row)
                continue
            a, b = norm(got), norm(q['answer'])
            (ok if (a == b or a in b or b in a) else bad).append(row)
    out = ['대조 %d · 일치 %d · 불일치 %d · 정답지에 없음 %d'
           % (len(ok) + len(bad) + len(miss), len(ok), len(bad), len(miss)), '']
    for title, rows in [('불일치', bad), ('정답지 못 읽음', miss)]:
        out.append('── %s ──' % title)
        for t, i, src, no, got, mine in rows:
            out.append('%s %2d번  %s %2d번  정답지 %-8s  내해설 %s'
                       % (t[:5], i, src, no, got if got else '-', mine))
        out.append('')
    io.open('_verify.txt', 'w', encoding='utf-8').write('\n'.join(out))
    json.dump([['%s_%02d' % (r[2], r[3]), r[0], r[1], r[5]] for r in miss],
              io.open('_todo3.json', 'w', encoding='utf-8'), ensure_ascii=False)


if __name__ == '__main__':
    main()
