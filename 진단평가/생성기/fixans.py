def main():
    log = []
    for f, fixes in FIX.items():
        s = json.load(io.open(f, encoding='utf-8'))
        for no, (ans, steps, miss) in fixes.items():
            q = s['questions'][no - 1]
            log.append('%s %2d번  %s → %s' % (s['title'], no, q['answer'], ans))
            q['answer'] = ans
            q['steps'] = steps.split('|') if isinstance(steps, str) else steps
            q['miss'] = miss
        json.dump(s, io.open(f, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    io.open('_fixed.txt', 'w', encoding='utf-8').write('\n'.join(log))
    print('%d문항 정정' % len(log))


if __name__ == '__main__':
    main()
